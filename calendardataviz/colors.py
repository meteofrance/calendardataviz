from calendardataviz.rich_string import RichString


def color_from_pct(pct: float, colors: list[RichString]) -> RichString:
    """Returns a color from the given color list, corresponding
    to the given percentage.

    Args:
        pct: A float between 0 and 1.
        colors: A list of colors, ordered to form a color bar.

    Returns:
        RichString:
    """
    # Restricts between 0 and 1
    pct = min(1, max(pct, 0))
    keys = [i / (len(colors) - 1) for i in range(len(colors))]
    closest_pct = min(keys, key=lambda x: abs(x - pct))

    return colors[keys.index(closest_pct)]


